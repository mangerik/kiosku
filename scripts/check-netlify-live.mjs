import assert from 'node:assert/strict';
import { readFile, writeFile } from 'node:fs/promises';
import { loadEnv } from 'vite';
const env = loadEnv('production', process.cwd(), 'VITE_');
const server = Object.fromEntries((await readFile('supabase/.env.local', 'utf8')).split(/\r?\n/).filter(line => line.includes('=')).map(line => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1)]));
const slug = process.argv[2];
assert(slug, 'Pass the known QA store slug.');
const publicResponse = await fetch(`${env.VITE_SUPABASE_URL}/rest/v1/rpc/public_storefront`, {method: 'POST', headers: {apikey: env.VITE_SUPABASE_ANON_KEY, Authorization: `Bearer ${env.VITE_SUPABASE_ANON_KEY}`, 'Content-Type': 'application/json'}, body: JSON.stringify({store_slug: slug})});
assert.equal(publicResponse.status, 200);
const payload = await publicResponse.json();
const store = payload.store;
assert(store?.publicUrl, 'Store must be published.');
assert.equal(store.deployment, null);
const page = await fetch(store.publicUrl);
assert.equal(page.status, 200);
assert((await page.text()).includes(`content="${store.id}"`));
const productPath = `/toko/${slug}/produk/${payload.products[0].id}`;
assert.equal((await fetch(`${store.publicUrl}${productPath}`)).status, 200);
const preflight = await fetch(`${env.VITE_SUPABASE_URL}/functions/v1/checkout`, {method: 'OPTIONS', headers: {Origin: store.publicUrl, 'Access-Control-Request-Method': 'POST'}});
assert.equal(preflight.headers.get('access-control-allow-origin'), store.publicUrl);
const badOrigin = 'https://unregistered-kiosku-test.netlify.app';
const blocked = await fetch(`${env.VITE_SUPABASE_URL}/functions/v1/checkout`, {method: 'OPTIONS', headers: {Origin: badOrigin}});
assert.notEqual(blocked.headers.get('access-control-allow-origin'), badOrigin);
async function netlify(path) {
  const r = await fetch(`https://api.netlify.com/api/v1${path}`, {headers: {Authorization: `Bearer ${server.NETLIFY_AUTH_TOKEN}`}});
  assert.equal(r.status, 200);
  return r.json();
}
const site = await netlify(`/sites/${new URL(store.publicUrl).hostname}`);
const deployments = await netlify(`/sites/${site.id}/deploys`);
assert.equal(site.account_slug, server.NETLIFY_TEAM_SLUG);
assert.equal(deployments[0].state, 'ready');
const main = JSON.parse(await readFile('docs/deployment/netlify-main.json', 'utf8'));
const mainDeploy = await netlify(`/deploys/${main.deployId}`);
assert.equal(mainDeploy.state, 'ready');
main.state = mainDeploy.state;
await writeFile('docs/deployment/netlify-main.json', JSON.stringify(main, null, 2));
const result = {checkedAt: new Date().toISOString(), storeId: store.id, storeUrl: store.publicUrl, siteId: site.id, deployId: deployments[0].id, deployCount: deployments.length, state: deployments[0].state, rootBinding: true, deepLink: productPath, registeredCors: true, unregisteredCorsRejected: true, mainReady: true};
await writeFile('docs/deployment/netlify-checks.json', JSON.stringify(result, null, 2));
console.log(JSON.stringify(result, null, 2));
